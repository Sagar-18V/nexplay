"""Unit tests for the auth primitives that must behave exactly like the Node versions."""
import asyncio
import os

os.environ.setdefault("DATABASE_URL", "postgresql://u:p@localhost:1/x")
os.environ.setdefault("REDIS_URL", "redis://localhost:1")
os.environ.setdefault("JWT_SECRET", "unit-test-secret")

import jwt
import pytest

from app.core.http import js_truthy
from app.core.security import create_access_token, decode_access_token, hash_password, verify_password


@pytest.mark.parametrize("value,expected", [
    (None, False), (False, False), (0, False), (0.0, False), (float("nan"), False), ("", False),
    ("x", True), (1, True), (-1, True), ([], True), ({}, True), (True, True),
])
def test_js_truthy_matches_javascript(value, expected):
    assert js_truthy(value) is expected


def test_access_token_has_node_claims_and_15min_ttl():
    claims = decode_access_token(create_access_token("m-1", "ADMIN"))
    assert set(claims) == {"merchantId", "role", "iat", "exp"}
    assert claims["exp"] - claims["iat"] == 15 * 60
    assert jwt.get_unverified_header(create_access_token("m-1", "ADMIN"))["alg"] == "HS256"


def test_token_signed_with_other_secret_is_rejected():
    forged = jwt.encode({"merchantId": "m-1", "role": "ADMIN"}, "attacker", algorithm="HS256")
    with pytest.raises(jwt.InvalidTokenError):
        decode_access_token(forged)


def test_alg_none_is_rejected():
    unsigned = jwt.encode({"merchantId": "m-1", "role": "ADMIN"}, key="", algorithm="none")
    with pytest.raises(jwt.InvalidTokenError):
        decode_access_token(unsigned)


def test_bcryptjs_hash_verifies():
    # Generated by the backend's own bcryptjs: require('bcryptjs').hashSync('password123', 10)
    node_hash = "$2b$10$ARs.JwuFB2YsVEMegfKBm.BIWn4oMi/zXNcflnjje0HJrukmvsB9y"
    assert asyncio.run(verify_password("password123", node_hash)) is True
    assert asyncio.run(verify_password("wrong-password", node_hash)) is False


def test_passwords_over_72_bytes_behave_like_bcryptjs():
    # bcryptjs ignores bytes after 72; so must we, or long passwords lock users out.
    long_pw = "x" * 80
    hashed = asyncio.run(hash_password(long_pw))
    assert asyncio.run(verify_password("x" * 72 + "DIFFERENT", hashed)) is True

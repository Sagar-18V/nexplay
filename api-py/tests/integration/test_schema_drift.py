"""
Schema drift guard: SQLAlchemy models vs the live database.

Steps 1-6: Prisma owned the schema, so this caught a Prisma migration without a model change.
Step 7+:   Alembic owns it. The strongest check is now `test_autogenerate_is_a_no_op`: if the
models and the migrated database differ in ANY way Alembic can see (columns, types, FKs and
their ON DELETE/UPDATE actions, unique and plain indexes, names), autogenerate would emit a
migration, and this fails, before someone ships a destructive autogenerated revision.

Runs only when TEST_DATABASE_URL points at a migrated database (`python -m app.ops.migrate`):
    TEST_DATABASE_URL=postgresql://nexpay@localhost:5432/nexpay pytest tests/integration
"""
import os

import pytest
from sqlalchemy import BigInteger, Boolean, Date, Integer, Text, create_engine, inspect, text
from sqlalchemy.dialects.postgresql import ENUM, JSONB, TIMESTAMP

from app.db.models import Base

DB_URL = os.getenv("TEST_DATABASE_URL")
pytestmark = pytest.mark.skipif(not DB_URL, reason="TEST_DATABASE_URL not set")

BOOKKEEPING = {"_prisma_migrations", "alembic_version"}


def _kind(t) -> str:
    """Normalise a column type to a comparable label."""
    if isinstance(t, ENUM):
        return f"enum:{t.name}"
    if isinstance(t, TIMESTAMP):
        return f"timestamp({t.precision},tz={bool(t.timezone)})"
    for cls, label in ((JSONB, "jsonb"), (BigInteger, "bigint"), (Integer, "integer"),
                       (Boolean, "boolean"), (Date, "date"), (Text, "text")):
        if isinstance(t, cls):
            return label
    return type(t).__name__.lower()


@pytest.fixture(scope="module")
def db():
    url = DB_URL.replace("postgresql://", "postgresql+psycopg://", 1)
    engine = create_engine(url)
    with engine.connect() as conn:
        yield conn
    engine.dispose()


def test_tables_match(db):
    live = set(inspect(db).get_table_names()) - BOOKKEEPING
    assert live == set(Base.metadata.tables), "table set differs between database and models"


@pytest.mark.parametrize("table", sorted(Base.metadata.tables))
def test_columns_match(db, table):
    model = Base.metadata.tables[table]
    live = {c["name"]: c for c in inspect(db).get_columns(table)}

    assert set(live) == set(model.columns.keys()), f"{table}: column names differ"
    for name, col in model.columns.items():
        assert _kind(col.type) == _kind(live[name]["type"]), f"{table}.{name}: type differs"
        assert col.nullable == live[name]["nullable"], f"{table}.{name}: nullability differs"


@pytest.mark.parametrize("table", sorted(Base.metadata.tables))
def test_foreign_keys_match(db, table):
    model = {
        (fk.parent.name, fk.column.table.name, fk.column.name)
        for fk in Base.metadata.tables[table].foreign_keys
    }
    live = {
        (fk["constrained_columns"][0], fk["referred_table"], fk["referred_columns"][0])
        for fk in inspect(db).get_foreign_keys(table)
    }
    assert model == live, f"{table}: foreign keys differ"


def test_enum_labels_match(db):
    rows = db.execute(text(
        "SELECT t.typname, e.enumlabel FROM pg_type t "
        "JOIN pg_enum e ON e.enumtypid = t.oid ORDER BY t.typname, e.enumsortorder"
    )).all()
    live: dict[str, set[str]] = {}
    for typname, label in rows:
        live.setdefault(typname, set()).add(label)

    model: dict[str, set[str]] = {}
    for tbl in Base.metadata.tables.values():
        for col in tbl.columns:
            if isinstance(col.type, ENUM):
                model[col.type.name] = set(col.type.enums)

    assert set(model) <= set(live), "model references an enum type the database lacks"
    for name, labels in model.items():
        assert labels == live[name], f"enum {name}: labels differ"


def test_autogenerate_is_a_no_op(db):
    from alembic.autogenerate import compare_metadata
    from alembic.migration import MigrationContext

    ignore_prisma_history = lambda name, type_, _parents: not (type_ == "table" and name == "_prisma_migrations")
    ctx = MigrationContext.configure(db, opts={"compare_type": True, "include_name": ignore_prisma_history})
    diffs = compare_metadata(ctx, Base.metadata)
    assert diffs == [], f"models and database differ; autogenerate would emit: {diffs}"


def test_database_is_at_alembic_head(db):
    from pathlib import Path

    from alembic.config import Config
    from alembic.script import ScriptDirectory

    head = ScriptDirectory.from_config(Config(str(Path(__file__).parents[2] / "alembic.ini"))).get_current_head()
    current = db.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
    assert current == head, f"database at {current}, code expects {head}: run python -m app.ops.migrate"


def test_idempotency_keys_are_unique_per_merchant(db):
    for table in ("payment_intents", "refunds"):
        unique = {tuple(ix["column_names"]) for ix in inspect(db).get_indexes(table) if ix["unique"]}
        assert ("merchantId", "idempotencyKey") in unique, f"{table}: per-merchant unique index missing"
        assert ("idempotencyKey",) not in unique, f"{table}: global unique index still present (D14/D20)"

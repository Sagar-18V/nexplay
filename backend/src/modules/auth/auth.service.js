const bcrypt = require('bcryptjs');
const jwt = require('jsonwebtoken');
const { v4: uuidv4 } = require('uuid');
const prisma = require('../../config/prisma');
const redis = require('../../config/redis');

const ACCESS_TOKEN_TTL = '15m';
const REFRESH_TOKEN_TTL = 7 * 24 * 60 * 60; // 7 days in seconds

function refreshKey(token) {
    return `refresh:${token}`;
}

function generateAccessToken(merchant) {
    // `merchant` may be a full record or a minimal { id, role }
    return jwt.sign(
        { merchantId: merchant.id, role: merchant.role },
        process.env.JWT_SECRET,
        { expiresIn: ACCESS_TOKEN_TTL }
    );
}

// Issue a brand-new refresh token and persist it in Redis with a TTL.
// Stores both the merchantId and role so refresh can re-mint an access token
// without an extra DB round-trip.
async function issueRefreshToken(merchant) {
    const token = uuidv4();
    await redis.setex(
        refreshKey(token),
        REFRESH_TOKEN_TTL,
        JSON.stringify({ merchantId: merchant.id, role: merchant.role })
    );
    return token;
}

async function register({ name, email, password, webhookUrl }) {
    const existing = await prisma.merchant.findUnique({ where: { email } });
    if (existing) {
        const err = new Error('Email already registered');
        err.status = 409;
        throw err;
    }

    const hashedPassword = await bcrypt.hash(password, 10);

    const merchant = await prisma.merchant.create({
        data: {
            name,
            email,
            password: hashedPassword,
            webhookUrl: webhookUrl || null,
            // role defaults to MERCHANT; apiKey auto-generated by Prisma default(uuid())
        },
        select: {
            id: true,
            name: true,
            email: true,
            role: true,
            apiKey: true,
            webhookUrl: true,
            createdAt: true
        }
    });

    return merchant;
}

async function login({ email, password }) {
    const merchant = await prisma.merchant.findUnique({ where: { email } });

    if (!merchant || !merchant.isActive) {
        const err = new Error('Invalid credentials');
        err.status = 401;
        throw err;
    }

    const valid = await bcrypt.compare(password, merchant.password);
    if (!valid) {
        const err = new Error('Invalid credentials');
        err.status = 401;
        throw err;
    }

    const accessToken = generateAccessToken(merchant);
    const refreshToken = await issueRefreshToken(merchant);

    return {
        accessToken,
        refreshToken,
        merchant: {
            id: merchant.id,
            name: merchant.name,
            email: merchant.email,
            role: merchant.role,
            apiKey: merchant.apiKey
        }
    };
}

// Rotating refresh: the presented token is consumed and replaced with a fresh
// one. This limits the window a leaked refresh token is usable and lets us
// detect reuse of an already-rotated token (it will simply be absent).
async function refresh(token) {
    const raw = await redis.get(refreshKey(token));

    if (!raw) {
        const err = new Error('Invalid or expired refresh token');
        err.status = 401;
        throw err;
    }

    // Backwards-compatible parse: older tokens stored just the merchantId string.
    let session;
    try {
        session = JSON.parse(raw);
        if (typeof session !== 'object' || session === null) {
            session = { merchantId: raw };
        }
    } catch {
        session = { merchantId: raw };
    }

    // Revoke the old token (rotation).
    await redis.del(refreshKey(token));

    // Re-read role from DB so a role change takes effect on next refresh,
    // and to confirm the merchant is still active.
    const merchant = await prisma.merchant.findUnique({
        where: { id: session.merchantId },
        select: { id: true, role: true, isActive: true }
    });

    if (!merchant || !merchant.isActive) {
        const err = new Error('Merchant not found or inactive');
        err.status = 401;
        throw err;
    }

    const accessToken = generateAccessToken(merchant);
    const refreshToken = await issueRefreshToken(merchant);

    return { accessToken, refreshToken };
}

// Revoke a single refresh token (server-side logout).
async function logout(token) {
    if (!token) return;
    await redis.del(refreshKey(token));
}

module.exports = { register, login, refresh, logout };

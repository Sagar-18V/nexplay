const bcrypt = require('bcryptjs');
const jwt = require('jsonwebtoken');
const { v4: uuidv4 } = require('uuid');
const prisma = require('../../config/prisma');
const redis = require('../../config/redis');

const ACCESS_TOKEN_TTL = '15m';
const REFRESH_TOKEN_TTL = 7 * 24 * 60 * 60; // 7 days in seconds

function generateAccessToken(merchantId) {
    return jwt.sign(
        { merchantId },
        process.env.JWT_SECRET,
        { expiresIn: ACCESS_TOKEN_TTL }
    );
}

async function register({ name, email, password, webhookUrl }) {
    // check duplicate
    const existing = await prisma.merchant.findUnique({ where: { email } });
    if (existing) {
        const err = new Error('Email already registered');
        err.status = 409;
        throw err;
    }

    const hashedPassword = await bcrypt.hash(password, 10);

    const merchant = await prisma.merchant.create({
        data: {
            name,
            email,
            password: hashedPassword,
            webhookUrl: webhookUrl || null,
            // apiKey is auto-generated by Prisma default(uuid())
        },
        select: {
            id: true,
            name: true,
            email: true,
            apiKey: true,
            webhookUrl: true,
            createdAt: true
        }
    });

    return merchant;
}

async function login({ email, password }) {
    const merchant = await prisma.merchant.findUnique({ where: { email } });

    if (!merchant || !merchant.isActive) {
        const err = new Error('Invalid credentials');
        err.status = 401;
        throw err;
    }

    const valid = await bcrypt.compare(password, merchant.password);
    if (!valid) {
        const err = new Error('Invalid credentials');
        err.status = 401;
        throw err;
    }

    const accessToken = generateAccessToken(merchant.id);

    // store refresh token in Redis with TTL
    const refreshToken = uuidv4();
    await redis.setex(
        `refresh:${refreshToken}`,
        REFRESH_TOKEN_TTL,
        merchant.id
    );

    return {
        accessToken,
        refreshToken,
        merchant: {
            id: merchant.id,
            name: merchant.name,
            email: merchant.email,
            apiKey: merchant.apiKey
        }
    };
}

async function refresh(token) {
    // look up refresh token in Redis
    const merchantId = await redis.get(`refresh:${token}`);

    if (!merchantId) {
        const err = new Error('Invalid or expired refresh token');
        err.status = 401;
        throw err;
    }

    const accessToken = generateAccessToken(merchantId);
    return { accessToken };
}

module.exports = { register, login, refresh };